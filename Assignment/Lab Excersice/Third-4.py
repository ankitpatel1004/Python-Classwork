# type of a variable dynamically using type()

language = "Python"
print(type(language))
version = 3.14
print(type(version))
coupan = "3+k9"
print(type(coupan))
series = [100, 200, 300]
print(type(series))
new_series = (120, 240 ,360)
print(type(new_series))
author_detail = {"name":"Guido van rossum"}
print(type(author_detail))
is_exist = True
print(type(is_exist))
